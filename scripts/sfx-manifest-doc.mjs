/**
 * Generate `docs/SFX_FILE_MANIFEST.md` — the recording worksheet.
 *
 * Every row is one sound the game triggers, the filename base to record it
 * against, and what it is for.  Generated from the LIVE registry in a real
 * browser rather than written by hand, so it cannot drift from the code the
 * way a hand-maintained list would; the trigger/character columns come from
 * `docs/SFX_INVENTORY.md`, which is the design source of truth.
 *
 *   npm run build && npx vite preview --port 4173 --host 127.0.0.1 &
 *   node scripts/sfx-manifest-doc.mjs
 */
import { chromium } from 'playwright';
import { readFileSync, writeFileSync } from 'fs';

const URL = process.env.SMOKE_URL || 'http://127.0.0.1:4173/';

// ── Pull the id list and per-id config out of the running game ──────────────
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined });
const page = await browser.newPage();
await page.goto(URL, { waitUntil: 'networkidle' });
await page.mouse.click(195, 700);
await page.waitForFunction(() => window.__omniEngine?.audio?.audible === true, { timeout: 15000 });
// Decode is async and lands whenever it lands.  Reading the coverage count
// before it settles reports zero recordings and looks exactly like "none
// installed" — wait for the fetches to quiesce first.
await page.waitForFunction(
  () => { const a = window.__omniEngine.audio;
          return a.sampleCount + a.rejectedSampleCount > 0 || a.allIds.length === 0; },
  { timeout: 8000 },
).catch(() => { /* genuinely none installed — a legitimate state */ });
const live = await page.evaluate(() => {
  const a = window.__omniEngine.audio;
  const out = [];
  for (const [id, def] of a.defs) {
    out.push({ id, kind: 'one-shot', tier: def.tier, poly: def.poly,
               positional: !!def.positional, ms: Math.round(def.minInterval * 1000) });
  }
  for (const [id, def] of a.loopDefs) {
    out.push({ id, kind: 'loop', tier: def.tier, poly: 1,
               positional: !!def.positional, ms: 0 });
  }
  return { defs: out, sampled: a.sampledIds };
});
await browser.close();

// ── Trigger + character prose from the inventory document ───────────────────
const inv = readFileSync('docs/SFX_INVENTORY.md', 'utf8');
const prose = new Map();
// The inventory's rows are FIXED-COLUMN, so read them by position rather
// than by guessing which cell looks like prose:
//   1 id | 2 trigger | 3 tier | 4 dur | 5 character | 6 freq | 7 variation
//   | 8 poly | 9 mix | 10 positional
for (const line of inv.split('\n')) {
  const t = line.trim();
  if (!t.startsWith('|')) continue;
  const cells = t.split('|').map(c => c.trim());
  const id = (cells[1] || '').replace(/`/g, '');
  if (!/^[a-z]+\.[a-z0-9.]+$/i.test(id)) continue;
  if (prose.has(id)) continue;
  prose.set(id, { dur: cells[4] || '', character: cells[5] || '' });
}

const sampled = new Set(live.sampled);
const SECTIONS = [
  ['weapon.',  'Weapons — the player firing'],
  ['impact.',  'Impacts — shots landing'],
  ['crash.',   'Collisions — bodies hitting things'],
  ['destroy.', 'Destruction — things dying'],
  ['pickup.',  'Pickups and rewards'],
  ['move.',    'Movement and materials'],
  ['portal.',  'Portals'],
  ['poi.',     'Stations and points of interest'],
  ['snitch.',  'The snitch'],
  ['dragon.',  'The dragon'],
  ['rival.',   'Rival ships'],
  ['bubble.',  'Bubbles'],
  ['boss.',    'Bosses'],
  ['wave.',    'Waves'],
  ['shield.',  'Shields and status'],
  ['status.',  'Shields and status'],
  ['ui.',      'Interface'],
  ['',         'Everything else'],
];

const sectionOf = id => (SECTIONS.find(([p]) => p && id.startsWith(p)) || SECTIONS[SECTIONS.length - 1])[1];
const groups = new Map();
for (const d of live.defs) {
  const s = sectionOf(d.id);
  if (!groups.has(s)) groups.set(s, []);
  groups.get(s).push(d);
}

let md = `# Recording worksheet — one row per sound the game makes

**Generated by \`scripts/sfx-manifest-doc.mjs\` from the live registry.** Do
not hand-edit; re-run it instead. \`docs/SFX_INVENTORY.md\` remains the design
source of truth for how each sound should behave.

## How to add a sound

Drop a \`.wav\` into \`public/assets/sfx/\` named after the id, **dots replaced
by dashes**, plus any suffix you like:

\`\`\`
crash.player.shard   ->   crash-player-shard.wav
                          crash-player-shard-a.wav
                          crash-player-shard-rice-02.wav
\`\`\`

Nothing else is needed — no code change, no registry edit. Every file matching
an id is picked up automatically and **cycled round-robin**, so record as many
takes per action as you like; more takes means less repetition in bulk.

Then:

\`\`\`bash
node scripts/prep-sfx.mjs public/assets/sfx/*.wav   # trim, normalise, 16-bit mono
node scripts/smoke/assets.mjs                       # check they are usable
\`\`\`

To hear **only** your recordings with no synth underneath, open the pause menu
and press **Drafts ON** so it reads **WAV only**. Every id without a file goes
silent, and the counter beside it shows coverage.

## Reading the table

- **Tier** — mix priority. 1 never gets thinned under load; 3 is thinned first.
  Tier 1 is where recording effort pays off most.
- **Poly** — how many can sound at once. A low number with a high trigger rate
  means keep it SHORT (a voice holds its slot for the whole file).
- **Pos** — positional: panned and distance-attenuated, so record it dry and
  mono. Flat sounds are UI and can be wider.

Sounds already carrying at least one recorded take are marked ✅.

`;

let total = 0;
for (const [, section] of SECTIONS) {
  const rows = groups.get(section);
  if (!rows || rows.__done) continue;
  groups.set(section, Object.assign(rows, { __done: true }));
  md += `\n## ${section}\n\n`;
  md += `| | Sound id | File to create | Tier | Poly | ms | Pos | What it should sound like |\n`;
  md += `|---|---|---|---|---|---|---|---|\n`;
  for (const d of rows.sort((a, b) => a.id.localeCompare(b.id))) {
    total++;
    const p = prose.get(d.id) || {};
    const character = (p.character || '').replace(/\|/g, '/');
    md += `| ${sampled.has(d.id) ? '✅' : ''} | \`${d.id}\` | \`${d.id.replace(/\./g, '-')}-a.wav\` `
        + `| ${d.tier} | ${d.kind === 'loop' ? 'loop' : d.poly} | ${p.dur || ''} `
        + `| ${d.positional ? '•' : ''} | ${character} |\n`;
  }
}

md += `\n---\n\n**${total} sounds**, ${live.sampled.length} with at least one recorded take.\n`;

writeFileSync('docs/SFX_FILE_MANIFEST.md', md);
console.log(`wrote docs/SFX_FILE_MANIFEST.md — ${total} sounds, ${live.sampled.length} recorded`);
